/**
 * 조회 중 표시 (r58, 2026-09-14)
 *
 * `docs/ui_design.md` 5절 8번 — *"`Loading` 조회 중 표시"*. 4상태 중
 * **LOADING**을 맡는다(5-9절 표).
 *
 * ## 지금은 스켈레톤을 만들지 않는다
 *
 * 5절이 *"스켈레톤(목록·표) / 스피너(버튼·부분 갱신)"* **두 벌**을
 * 요구하지만, 현재 표본 다섯 곳이 **전부 텍스트 한 줄**이다. 스켈레톤은
 * 목록·표의 **모양을 알아야** 만들 수 있고 표가 있는 화면
 * (`/cleaning`·`/settlements`)이 아직 없다. 모양을 모르는 채 만들면
 * 첫 사용처에서 다시 만들게 된다.
 *
 * ## 문구를 컴포넌트가 조립한다
 *
 * 호출부는 **무엇을 불러오는지**(`label`)만 넘긴다. `"…불러오는 중…"`을
 * 호출부마다 쓰면 지금처럼 다섯 가지 문구가 생긴다 — 실제로
 * `불러오는 중…` / `숙소 불러오는 중…` / `숙소 목록 불러오는 중…` /
 * `객실 구성 불러오는 중…` 넷이 갈려 있었다.
 *
 * ## 바깥 여백을 스스로 정하지 않는다
 *
 * 페이지 최상단이냐 섹션 안이냐에 따라 달라야 한다(`p-6` / `mt-4` /
 * `mt-2`가 실제로 다 쓰이고 있었다). 컴포넌트가 정하면 쓰는 쪽이 매번
 * 상쇄용 클래스를 붙이게 되므로 **바깥 여백은 호출부의 것**으로 둔다.
 */

export interface LoadingProps {
  /** 무엇을 불러오는가. 예: `"객실 구성"` → `"객실 구성 불러오는 중…"` */
  label: string;
  /**
   * 최초 로딩이 아니라 **재시도 중**인가.
   *
   * 대시보드 카드가 쓰던 구분이다 — 사용자가 [다시 시도]를 누른 뒤
   * 아무 변화가 없으면 눌린 것인지 알 수 없다.
   */
  retrying?: boolean;
}

export default function Loading({ label, retrying = false }: LoadingProps) {
  return (
    <p className="text-sm text-gray-500">
      {label} {retrying ? "다시 불러오는 중…" : "불러오는 중…"}
    </p>
  );
}
